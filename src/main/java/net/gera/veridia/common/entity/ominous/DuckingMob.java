package net.gera.veridia.common.entity.ominous;

/**
 * Моб, который пригибается в низких проходах. Поиск пути ({@link MagmaWalkingNavigation}) считает высоту прохода по
 * росту пригнувшегося моба, а пригибается он сам, когда подходит к низкому месту.
 */
public interface DuckingMob {
    /** Рост пригнувшегося моба в блоках. */
    float duckingHeight();

    /**
     * Для поиска пути, который сейчас начнётся: насколько дороже клетка, где пришлось бы идти пригнувшись (обычный шаг
     * стоит около 1). Чем больше, тем охотнее моб обходит низкие места. Меньше нуля - такие клетки непроходимы.
     */
    float duckingPathMalus();
}
